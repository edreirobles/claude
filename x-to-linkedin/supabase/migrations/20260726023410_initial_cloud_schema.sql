create or replace function app.fail_job(
  p_job_id bigint,
  p_lease_token uuid,
  p_error text
)
returns text
language plpgsql
security definer
set search_path = app, pg_catalog
as $$
declare
  v_attempts integer;
  v_max_attempts integer;
  v_status text;
begin
  select attempts, max_attempts
  into v_attempts, v_max_attempts
  from app.job_queue
  where id = p_job_id
    and lease_token = p_lease_token
    and status in ('claimed', 'running')
  for update;
  if not found then
    return 'dead';
  end if;

  v_status := case when v_attempts >= v_max_attempts then 'dead' else 'retry_wait' end;
  update app.job_queue
  set status = v_status,
      run_at = case
        when v_status = 'retry_wait'
          then now() + make_interval(secs => least(3600, 60 * power(2, greatest(v_attempts - 1, 0))::integer))
        else run_at
      end,
      last_error = left(p_error, 2000),
      completed_at = case when v_status = 'dead' then now() else null end,
      leased_until = null,
      lease_owner = null
  where id = p_job_id;
  return v_status;
end;
$$;

create or replace function app.recover_expired_leases()
