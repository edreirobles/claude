create or replace function app.enqueue_job(
  p_job_type text,
  p_run_at timestamptz,
  p_payload jsonb,
  p_dedupe_key text,
  p_max_attempts integer default 5,
  p_priority integer default 100,
  p_correlation_id uuid default null
)
returns bigint
language plpgsql
security definer
set search_path = app, extensions, pg_catalog
as $$
declare
  v_id bigint;
begin
  insert into app.job_queue (
    job_type, run_at, payload, dedupe_key, max_attempts, priority, correlation_id
  ) values (
    p_job_type, p_run_at, coalesce(p_payload, '{}'::jsonb), p_dedupe_key,
    greatest(1, least(p_max_attempts, 20)), p_priority, p_correlation_id
  )
  on conflict (dedupe_key) do update
    set updated_at = now()
  returning id into v_id;
  return v_id;
end;
$$;

create or replace function app.approve_post(
  p_post_id bigint,
  p_actor text default 'telegram'
)
returns table (
  post_id bigint,
  status text,
  publish_at timestamptz,
  job_id bigint,
  already_processed boolean
)
language plpgsql
security definer
set search_path = app, extensions, pg_catalog
as $$
declare
  v_post app.posts%rowtype;
  v_now timestamptz := clock_timestamp();
  v_publish_at timestamptz;
  v_job_id bigint;
begin
  select * into v_post from app.posts where id = p_post_id for update;
  if not found then
    raise exception 'post_not_found' using errcode = 'P0002';
  end if;

  if v_post.status in ('scheduled', 'publishing', 'published') and v_post.approved_at is not null then
    select id into v_job_id
    from app.job_queue
    where dedupe_key = 'publish_post:' || p_post_id::text;
    return query select v_post.id, v_post.status, v_post.publish_at, v_job_id, true;
    return;
  end if;

  if v_post.status <> 'approval_pending' then
    raise exception 'post_not_approval_pending' using errcode = 'P0001';
  end if;

  v_publish_at := v_now + interval '30 minutes';
  update app.posts
  set
    approved_at = v_now,
    publish_at = v_publish_at,
    scheduled_at = v_publish_at,
    status = 'scheduled',
    media_type = case when media_type = 'auto' then 'none' else media_type end,
    generated_image_path = null,
    manual_edited_at = v_now,
    manual_edited_via = coalesce(manual_edited_via, p_actor),
    error_message = null,
    version = version + 1
  where id = p_post_id
  returning * into v_post;

  v_job_id := app.enqueue_job(
    'publish_post',
    v_publish_at,
    jsonb_build_object('post_id', p_post_id),
    'publish_post:' || p_post_id::text,
    5,
    10,
    null
  );
  return query select v_post.id, v_post.status, v_post.publish_at, v_job_id, false;
end;
$$;

create or replace function app.cancel_post(
  p_post_id bigint,
  p_actor text default 'dashboard'
)
returns text
language plpgsql
security definer
set search_path = app, pg_catalog
as $$
declare
  v_status text;
begin
  select status into v_status from app.posts where id = p_post_id for update;
  if not found then
    raise exception 'post_not_found' using errcode = 'P0002';
  end if;
  if v_status not in ('pending', 'radar_slot', 'approval_pending', 'scheduled', 'failed') then
    return v_status;
  end if;
  update app.posts
  set status = 'cancelled',
      error_message = 'Cancelled by ' || p_actor,
      version = version + 1
  where id = p_post_id;
  update app.job_queue
  set status = 'cancelled', completed_at = now()
  where status in ('pending', 'retry_wait', 'claimed')
    and payload @> jsonb_build_object('post_id', p_post_id);
  return 'cancelled';
end;
$$;

create or replace function app.append_revision_and_enqueue(
  p_post_id bigint,
  p_instruction text,
  p_actor text default 'telegram'
)
returns bigint
language plpgsql
security definer
set search_path = app, extensions, pg_catalog
as $$
declare
  v_notes text;
  v_version integer;
  v_job_id bigint;
  v_instruction text := btrim(p_instruction);
begin
  if v_instruction = '' or length(v_instruction) > 5000 then
    raise exception 'invalid_revision_instruction' using errcode = '22023';
  end if;

  select editorial_revision_notes, version
  into v_notes, v_version
  from app.posts
  where id = p_post_id and status = 'approval_pending'
  for update;
  if not found then
    raise exception 'post_not_approval_pending' using errcode = 'P0002';
  end if;

  if not exists (
    select 1
    from unnest(string_to_array(coalesce(v_notes, ''), E'\n')) as note
    where lower(btrim(note)) = lower(v_instruction)
  ) then
    v_notes := left(concat_ws(E'\n', nullif(v_notes, ''), v_instruction), 5000);
  end if;

  update app.posts
  set editorial_revision_notes = v_notes,
      manual_edited_at = now(),
      manual_edited_via = p_actor,
      version = version + 1
  where id = p_post_id
  returning version into v_version;

  v_job_id := app.enqueue_job(
    'revise_post',
    now(),
    jsonb_build_object('post_id', p_post_id),
    'revise_post:' || p_post_id::text || ':' || v_version::text,
    4,
    30,
    null
  );
  return v_job_id;
end;
$$;

create or replace function app.claim_due_jobs(
  p_worker_id text,
  p_limit integer default 5,
  p_lease_seconds integer default 900
)
returns table (
  id bigint,
  job_type text,
  payload jsonb,
  attempts integer,
  max_attempts integer,
  lease_token uuid,
  correlation_id uuid
)
language sql
security definer
set search_path = app, extensions, pg_catalog
as $$
  with due as (
    select q.id
    from app.job_queue q
    where q.status in ('pending', 'retry_wait')
      and q.run_at <= now()
    order by q.priority asc, q.run_at asc, q.id asc
    for update skip locked
    limit greatest(1, least(p_limit, 20))
  ),
  claimed as (
    update app.job_queue q
    set status = 'claimed',
        attempts = q.attempts + 1,
        lease_owner = p_worker_id,
        lease_token = extensions.gen_random_uuid(),
        leased_until = now() + make_interval(secs => greatest(30, least(p_lease_seconds, 900))),
        last_error = null
    from due
    where q.id = due.id
    returning q.id, q.job_type, q.payload, q.attempts, q.max_attempts,
              q.lease_token, q.correlation_id
  )
  select * from claimed;
$$;

