create or replace function app.consume_rate_limit(
  p_bucket_key text,
  p_limit integer,
  p_window_seconds integer
)
returns boolean
language plpgsql
security definer
set search_path = app, pg_catalog
as $$
declare
  v_count integer;
begin
  insert into app.rate_limits (bucket_key, window_started_at, request_count)
  values (p_bucket_key, now(), 1)
  on conflict (bucket_key) do update
    set window_started_at = case
          when app.rate_limits.window_started_at + make_interval(secs => p_window_seconds) <= now()
            then now()
          else app.rate_limits.window_started_at
        end,
        request_count = case
          when app.rate_limits.window_started_at + make_interval(secs => p_window_seconds) <= now()
            then 1
          else app.rate_limits.request_count + 1
        end
  returning request_count into v_count;
  return v_count <= p_limit;
end;
$$;

create or replace function app.schedule_periodic_jobs()
returns integer
language plpgsql
security definer
set search_path = app, pg_catalog
as $$
declare
  v_count integer := 0;
  v_id bigint;
  v_hour text := to_char(date_trunc('hour', now()), 'YYYYMMDDHH24');
  v_radar_bucket text :=
    to_char(date_trunc('day', now()), 'YYYYMMDD') || ':' ||
    floor(extract(hour from now()) / 6)::integer::text;
  v_cost_bucket text :=
    to_char(date_trunc('day', now()), 'YYYYMMDD') || ':' ||
    floor(extract(hour from now()) / 6)::integer::text;
begin
  v_id := app.enqueue_job(
    'comments_sync',
    now(),
    '{}'::jsonb,
    'comments_sync:' || v_hour,
    4,
    70,
    null
  );
  v_count := v_count + 1;

  v_id := app.enqueue_job(
    'cost_monitor',
    now(),
    '{}'::jsonb,
    'cost_monitor:' || v_cost_bucket,
    4,
    90,
    null
  );
  v_count := v_count + 1;

  v_id := app.enqueue_job(
    'radar_maintenance',
    now(),
    '{}'::jsonb,
    'radar_maintenance:' || v_radar_bucket,
    4,
    50,
    null
  );
  v_count := v_count + 1;

  v_id := app.enqueue_job(
    'metrics_refresh',
    now(),
    '{}'::jsonb,
    'metrics_refresh:' || to_char(now(), 'YYYYMMDD'),
    4,
    80,
    null
  );
  v_count := v_count + 1;
  return v_count;
end;
$$;

create or replace function app.dispatch_due_jobs()
returns bigint
language plpgsql
security definer
set search_path = app, vault, net, pg_catalog
as $$
declare
  v_due bigint;
  v_url text;
  v_secret text;
begin
  perform app.recover_expired_leases();
  perform app.schedule_periodic_jobs();

  select count(*) into v_due
  from app.job_queue
  where status in ('pending', 'retry_wait') and run_at <= now();
  if v_due = 0 then
    return 0;
  end if;

  select decrypted_secret into v_url
  from vault.decrypted_secrets where name = 'x2li_dispatch_url' limit 1;
  select decrypted_secret into v_secret
  from vault.decrypted_secrets where name = 'x2li_dispatch_secret' limit 1;
  if v_url is null or v_secret is null then
    raise exception 'dispatch_vault_secrets_missing';
  end if;

  perform net.http_post(
    url := v_url,
    headers := jsonb_build_object(
      'content-type', 'application/json',
      'x-dispatch-secret', v_secret
    ),
    body := jsonb_build_object('source', 'supabase_cron', 'due', v_due),
    timeout_milliseconds := 5000
  );
  return v_due;
end;
$$;

